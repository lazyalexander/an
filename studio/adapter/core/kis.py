import pathlib
import typing


class Document(typing.Protocol):
    def group(self, name: str, parent=None): ...

    def layer_from_png(self, name: str, parent, png_path: pathlib.Path): ...

    def set_locked(self, node, locked: bool) -> None: ...

    def save(self, path: pathlib.Path) -> None: ...


class Kis(typing.Protocol):
    def create_document(self, width: int, height: int, name: str) -> Document: ...
